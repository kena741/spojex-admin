export function searchEmojis(query: string, limit = 80): EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return EMOJI_CATALOG.slice(0, limit);
  const scored = EMOJI_CATALOG.map((entry) => {
    const hay = `${entry.name} ${entry.keywords} ${entry.emoji}`.toLowerCase();
    if (!hay.includes(q) && !entry.name.toLowerCase().startsWith(q)) return -1;
    let score = 0;
    if (entry.name.toLowerCase().startsWith(q)) score += 3;
    if (entry.name.toLowerCase().includes(q)) score += 2;
    if (entry.keywords.includes(q)) score += 1;
    return score;
  });
  return EMOJI_CATALOG.map((entry, i) => ({ entry, score: scored[i]! }))
    .filter((row) => row.score >= 0)
    .sort((a, b) => b.score - a.score || a.entry.name.localeCompare(b.entry.name))
    .slice(0, limit)
    .map((row) => row.entry);
}
